-- then VERIFIED or NOT VERIFIED. SnowSQL: !source sql/2_snapshot_verify.sql (shows the rows; no verdict).

-- name: LAST_RUN_OK (expect 1)
SELECT RUN_ID, FINISHED_AT, SOURCES, ROW_COUNTS, NOTES FROM &DB.&SCHEMA.TBL_ACCESS_RUN
QUALIFY ROW_NUMBER() OVER (ORDER BY STARTED_AT DESC) = 1 AND STATUS = 'OK';

-- name: ONE_RUN_IN_DATA (expect 1)
SELECT RUN_ID, COUNT(*) AS N FROM (
    SELECT RUN_ID FROM &DB.&SCHEMA.TBL_ACCESS_GRANT UNION ALL SELECT RUN_ID FROM &DB.&SCHEMA.TBL_ACCESS_USER_ROLE
    UNION ALL SELECT RUN_ID FROM &DB.&SCHEMA.TBL_ACCESS_USER UNION ALL SELECT RUN_ID FROM &DB.&SCHEMA.TBL_ACCESS_USAGE
    UNION ALL SELECT RUN_ID FROM &DB.&SCHEMA.TBL_ACCESS_TAG UNION ALL SELECT RUN_ID FROM &DB.&SCHEMA.TBL_ACCESS_POLICY
    UNION ALL SELECT RUN_ID FROM &DB.&SCHEMA.TBL_ACCESS_STREAM)
GROUP BY RUN_ID;

-- name: GRANTS_BY_TYPE
SELECT GRANTED_ON, IS_FUTURE, COUNT(*) AS N FROM &DB.&SCHEMA.TBL_ACCESS_GRANT GROUP BY 1, 2 ORDER BY 3 DESC;

-- name: USERS_WITH_ROLES
SELECT COUNT(DISTINCT USER_NAME) AS USERS, COUNT(*) AS GRANTS FROM &DB.&SCHEMA.TBL_ACCESS_USER_ROLE;

-- name: USAGE_BY_KIND
SELECT KIND, COUNT(*) AS N FROM &DB.&SCHEMA.TBL_ACCESS_USAGE GROUP BY 1;

-- name: TAGS_BY_DOMAIN
SELECT DOMAIN, APPLY_METHOD, COUNT(*) AS N FROM &DB.&SCHEMA.TBL_ACCESS_TAG GROUP BY 1, 2 ORDER BY 3 DESC;

-- name: POLICIES_BY_KIND
SELECT POLICY_KIND, COUNT(*) AS N, COUNT(POLICY_BODY) AS WITH_BODY FROM &DB.&SCHEMA.TBL_ACCESS_POLICY GROUP BY 1;

-- name: STREAMS
SELECT SOURCE_TYPE, COUNT(*) AS N FROM &DB.&SCHEMA.TBL_ACCESS_STREAM GROUP BY 1;
